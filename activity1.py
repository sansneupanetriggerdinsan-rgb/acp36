import seaborn as sns
import matplotlib.pyplot as plt
df = sns.load_dataset('tips')
df = df.dropna()
df = df.dropna()
print(df.head())
print(df.info())
sns.barplot(x='day', y='total_bill', hue='sex', data=df)
plt.title('Average Total Bill per Day by Gender')
plt.xlabel('Day')
plt.ylabel('Average Bill($)')
plt.show()
sns.countplot(x='day', hue='sex', data=df)
plt.title('Number of Diners per Day by Gender')
plt.xlabel('Day')
plt.ylabel('Count')
plt.show()

sns.boxplot(x='day', y='total bill', daat=df, jitter=True)
plt.title('Every Bill Amount per Day (Strip Plot)')
plt.xlabel('Day')
plt.ylabel('Total Bill($)')
plt.show()
sns.swarmplot(x='day', y='total_bill', data=df)
plt.title('Every Bill Amount per Day (Swarn Plot)')
plt.xlabel('Dry')
plt.ylabel('Total Bill ($)')
plt.show()

sns.jointplot(x='total_bill', y='tip', data=df)
plt.suptitle('Total Bill vs Tip', y=1.02)
plt.show()
sns.jointplot(x='total_bill',y='tip', data=df, kid='kde')
plt.suptitle('Total Bill vs tip - KDE Joint Plot', y=1.02)
plt.show()

sns.jointplot(x='total_bill', y='tip', data=df)
plt.suptitle('Total Bill vs Tip', y=1.02)
plt.show()
sns.jointplot(x='total_bill vs tip - KDEJoint Plot', y=1.02)
plt.show()

sns.pointplot(x='day', y='total_bill', hue='sex', data=df)
plt.title('average bill per day by gender')
plt.bar_label('day')
plt.ylabel('average bill($)')
plt.show()
sns.lmport(x='total_bill', y='tip', data= df)
plt.title('Total Bill vs Tip - Trend Life')
plt.show()